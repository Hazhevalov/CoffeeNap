    private readonly IAppNavigationService _navigationService;

    public PrivacyPolicyPage(IAppNavigationService navigationService)
    {
        var startedAt = PerformanceTrace.Start();
        InitializeComponent();
        PerformanceTrace.Elapsed("PrivacyPolicyPage.InitializeComponent", startedAt);
        PerformanceTrace.TrackFirstLayout(this, nameof(PrivacyPolicyPage), startedAt);

        _navigationService = navigationService;
        BindingContext = this;
        NavigationPage.SetHasNavigationBar(this, false);
    }

    private async void OnBackClicked(object? sender, EventArgs eventArgs)
        => await _navigationService.GoBackAsync();

    protected override void OnAppearing()
    {
        var startedAt = PerformanceTrace.Start();
        base.OnAppearing();
        PerformanceTrace.Elapsed("PrivacyPolicyPage.OnAppearing", startedAt);
    }

    protected override bool OnBackButtonPressed()
    {
        _ = _navigationService.GoBackAsync();
        return true;
